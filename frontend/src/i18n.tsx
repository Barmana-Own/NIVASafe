export function translate(key: string, locale: Locale = getCurrentLocale(), values: TranslationValues = {}): string {
  const value = (locale === "en" ? en[key] : fa[key]) ?? fa[key] ?? key;
  return value.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? `{{${name}}}`));
}

type I18nContextValue = { locale: Locale; direction: "ltr" | "rtl"; t: (key: string, values?: TranslationValues) => string; setLocale: (locale: Locale) => void };
const I18nContext = createContext<I18nContextValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => getCurrentLocale());
  function setLocale(next: Locale) {
    localStorage.setItem("nivasafe-locale", next);
    setLocaleState(next);
  }
  useEffect(() => {
    const direction = directionForLocale(locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = direction;
    document.documentElement.dataset.locale = locale;
  }, [locale]);
  const value: I18nContextValue = { locale, direction: directionForLocale(locale), t: (key, values) => translate(key, locale, values), setLocale };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("LocaleProvider is required");
  return context;
}

export function LanguageSwitcher({ className = "", onChange }: { className?: string; onChange?: (locale: Locale) => void }) {
  const { locale, setLocale, t } = useI18n();
  const [open, setOpen] = useState(false);
  const pickerRef = useRef<HTMLDivElement>(null);
  const triggerRef = useRef<HTMLButtonElement>(null);
  const menuRef = useRef<HTMLDivElement>(null);
  const optionRefs = useRef<Array<HTMLButtonElement | null>>([]);
  const menuId = `language-menu-${useId().replace(/:/g, "")}`;
  const options: Locale[] = ["fa", "en"];

  useEffect(() => {
    if (!open) return;
    const onPointerDown = (event: PointerEvent) => {
      if (pickerRef.current && !pickerRef.current.contains(event.target as Node)) setOpen(false);
    };
    const onKeyDown = (event: globalThis.KeyboardEvent) => {
      if (event.key === "Escape") {
        setOpen(false);
        triggerRef.current?.focus();
      }
    };
    document.addEventListener("pointerdown", onPointerDown);
    document.addEventListener("keydown", onKeyDown);
    optionRefs.current[options.indexOf(locale)]?.focus();
    return () => {
      document.removeEventListener("pointerdown", onPointerDown);
      document.removeEventListener("keydown", onKeyDown);
    };
  }, [open]);

  function chooseLocale(next: Locale) {
    setOpen(false);
    triggerRef.current?.focus();
    if (next !== locale) {
      setLocale(next);
      onChange?.(next);
    }
  }

  function handleOptionKeyDown(event: KeyboardEvent<HTMLButtonElement>, index: number) {
    if (event.key !== "ArrowDown" && event.key !== "ArrowUp" && event.key !== "Home" && event.key !== "End") return;
    event.preventDefault();
    const nextIndex = event.key === "Home" ? 0 : event.key === "End" ? options.length - 1 : event.key === "ArrowDown" ? (index + 1) % options.length : (index + options.length - 1) % options.length;
    optionRefs.current[nextIndex]?.focus();
  }

  return <div ref={pickerRef} className="language-picker">
    <button ref={triggerRef} type="button" className={`language-switch ${className}`.trim()} onClick={() => setOpen((value) => !value)} aria-label={t("language.choose")} aria-haspopup="menu" aria-expanded={open} aria-controls={menuId} title={t("language.choose")} data-testid="language-switcher">
      <span>{t(locale === "en" ? "language.english" : "language.persian")}</span><span className={`language-switch-chevron ${open ? "open" : ""}`} aria-hidden="true">⌄</span>
    </button>
    {open && <div ref={menuRef} id={menuId} className="language-menu" role="menu" aria-label={t("language.choose")}>
      <div className="language-menu-title">{t("language.choose")}</div>
      {options.map((option, index) => {
        const selected = option === locale;
        const label = t(option === "en" ? "language.english" : "language.persian");
        return <button key={option} ref={(element) => { optionRefs.current[index] = element; }} type="button" className={`language-option ${selected ? "selected" : ""}`} role="menuitemradio" aria-checked={selected} aria-label={selected ? `${label} — ${t("language.active")}` : label} onClick={() => chooseLocale(option)} onKeyDown={(event) => handleOptionKeyDown(event, index)}>
          <span>{label}</span>{selected && <span className="language-option-check" aria-hidden="true">✓</span>}
        </button>;
      })}
    </div>}
  </div>;
}

