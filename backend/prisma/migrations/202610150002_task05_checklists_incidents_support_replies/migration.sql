CREATE TABLE `ChecklistTemplate` (
  `id` VARCHAR(36) NOT NULL,
  `organizationId` VARCHAR(36) NOT NULL,
  `familyId` VARCHAR(36) NOT NULL,
  `version` INTEGER NOT NULL DEFAULT 1,
  `title` VARCHAR(191) NOT NULL,
  `description` TEXT NULL,
  `items` JSON NOT NULL,
  `status` VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
  `createdById` VARCHAR(36) NOT NULL,
  `publishedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `ChecklistTemplate_organizationId_familyId_version_key` (`organizationId`, `familyId`, `version`),
  INDEX `ChecklistTemplate_organizationId_status_updatedAt_idx` (`organizationId`, `status`, `updatedAt`),
  CONSTRAINT `ChecklistTemplate_organizationId_fkey` FOREIGN KEY (`organizationId`) REFERENCES `Organization` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `ChecklistTemplate_createdById_fkey` FOREIGN KEY (`createdById`) REFERENCES `User` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

