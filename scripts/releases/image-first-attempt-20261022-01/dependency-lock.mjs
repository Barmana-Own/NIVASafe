import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire}from'node:module';
import {root,work,evidence,sha}from'./prepare-proxy.mjs';
const before=fs.readFileSync(`${work}/pnpm-lock.before-undici.yaml`,'utf8');
const installResult=fs.readFileSync(`${root}/pnpm-lock.yaml`,'utf8');
const dependency='      undici:\n        specifier: 6.29.1\n        version: 6.29.1\n';
